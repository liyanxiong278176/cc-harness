"""Dynamic, durable child-run contracts and orchestration tools.

This module is deliberately small and provider-neutral.  The parent Agent owns
the task wording; the runtime only validates the safety/effect boundary and
persists the delegation before returning.  There is no in-process child-agent
runner here: child execution is always scheduled by the Durable Runtime.
"""

from __future__ import annotations

import json
from dataclasses import dataclass, field
from typing import Any, Mapping

from .mcp_client import ToolResult
from .run_model import EffectClass, digest_json


@dataclass(frozen=True)
class ChildTaskSpec:
    """A dynamic task generated by the parent Agent for one child Run."""

    node_id: str
    objective: str
    acceptance_criteria: tuple[str, ...] = ()
    description: str = ""
    required: bool = True
    depends_on: tuple[str, ...] = ()
    effect_class: EffectClass = EffectClass.READ_ONLY
    allowed_scope: tuple[str, ...] = ()
    excluded_scope: tuple[str, ...] = ()
    owned_paths: tuple[str, ...] = ()
    context_refs: tuple[str, ...] = ()
    budget: Mapping[str, Any] = field(default_factory=dict)
    timeout_seconds: int = 240
    max_retries: int = 1
    output_schema: Mapping[str, Any] = field(default_factory=dict)

    def __post_init__(self) -> None:
        if not self.node_id.strip():
            raise ValueError("child node_id is required")
        if not self.objective.strip():
            raise ValueError("child objective is required")
        if self.required and not self.acceptance_criteria:
            raise ValueError("required child tasks need acceptance_criteria")
        if any(not criterion.strip() for criterion in self.acceptance_criteria):
            raise ValueError("child acceptance_criteria must be non-empty strings")
        if self.timeout_seconds < 1 or self.timeout_seconds > 3600:
            raise ValueError("child timeout_seconds must be in [1, 3600]")
        if self.max_retries < 0 or self.max_retries > 2:
            raise ValueError("child max_retries must be in [0, 2]")
        if self.effect_class not in {
            EffectClass.READ_ONLY,
            EffectClass.WORKSPACE_MUTATION,
        }:
            raise ValueError("child effect_class must be read_only or workspace_mutation")
        if self.effect_class is EffectClass.WORKSPACE_MUTATION and not self.owned_paths:
            raise ValueError("mutating child tasks need owned_paths")
        for field_name, values in (
            ("allowed_scope", self.allowed_scope),
            ("excluded_scope", self.excluded_scope),
            ("owned_paths", self.owned_paths),
            ("context_refs", self.context_refs),
        ):
            if any(not value.strip() for value in values):
                raise ValueError(f"child {field_name} must not contain empty values")

    @classmethod
    def from_dict(cls, raw: Mapping[str, Any], *, index: int = 0) -> "ChildTaskSpec":
        if not isinstance(raw, Mapping):
            raise ValueError(f"sub_specs[{index}] must be an object")
        node_id = str(raw.get("node_id") or raw.get("task_id") or raw.get("id") or "")
        if not node_id:
            node_id = f"child-{index + 1}"
        criteria = raw.get("acceptance_criteria")
        if criteria is None:
            criteria = raw.get("criteria") or ()
        if isinstance(criteria, str):
            criteria = (criteria,)
        effect = raw.get("effect_class", EffectClass.READ_ONLY.value)
        try:
            effect_class = effect if isinstance(effect, EffectClass) else EffectClass(str(effect))
        except ValueError as exc:
            raise ValueError(f"sub_specs[{index}].effect_class is invalid") from exc
        return cls(
            node_id=node_id,
            objective=str(raw.get("objective") or raw.get("title") or ""),
            description=str(raw.get("description") or ""),
            acceptance_criteria=tuple(str(item) for item in criteria or ()),
            required=bool(raw.get("required", True)),
            depends_on=tuple(str(item) for item in raw.get("depends_on") or ()),
            effect_class=effect_class,
            allowed_scope=tuple(str(item) for item in raw.get("allowed_scope") or ()),
            excluded_scope=tuple(str(item) for item in raw.get("excluded_scope") or ()),
            owned_paths=tuple(str(item) for item in raw.get("owned_paths") or ()),
            context_refs=tuple(str(item) for item in raw.get("context_refs") or ()),
            budget=dict(raw.get("budget") or {}),
            timeout_seconds=int(raw.get("timeout_seconds", raw.get("timeout", 240))),
            max_retries=int(raw.get("max_retries", 1)),
            output_schema=dict(raw.get("output_schema") or {}),
        )

    @property
    def digest(self) -> str:
        return digest_json(self.to_dict())

    def to_dict(self) -> dict[str, Any]:
        return {
            "schema_version": "cc-harness.child-task.v1",
            "node_id": self.node_id,
            "objective": self.objective,
            "description": self.description,
            "acceptance_criteria": list(self.acceptance_criteria),
            "required": self.required,
            "depends_on": list(self.depends_on),
            "effect_class": self.effect_class.value,
            "allowed_scope": list(self.allowed_scope),
            "excluded_scope": list(self.excluded_scope),
            "owned_paths": list(self.owned_paths),
            "context_refs": list(self.context_refs),
            "budget": dict(self.budget),
            "timeout_seconds": self.timeout_seconds,
            "max_retries": self.max_retries,
            "output_schema": dict(self.output_schema),
        }


