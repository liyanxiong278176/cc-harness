async def durable_dispatch_subagent_handler(
    args: Mapping[str, Any], *, coordinator, run_id: str, **_: Any
) -> ToolResult:
    try:
        raw_specs = args.get("sub_specs") or ()
        max_fan_out = int(args.get("max_fan_out", 3))
        if not 1 <= max_fan_out <= 10:
            raise ValueError("max_fan_out must be in [1, 10]")
        if not 1 <= len(raw_specs) <= max_fan_out:
            raise ValueError(f"sub_specs length must be in [1, {max_fan_out}]")
        specs = tuple(ChildTaskSpec.from_dict(item, index=index) for index, item in enumerate(raw_specs))
        if len({spec.node_id for spec in specs}) != len(specs):
            raise ValueError("child node_id values must be unique")
        receipts = await coordinator.create_children(run_id, specs)
    except (TypeError, ValueError, KeyError) as exc:
        return ToolResult.error(str(exc), f"[Tool Error] durable child dispatch rejected: {exc}")
    payload = {
        "schema_version": "cc-harness.child-dispatch-result.v1",
        "parent_run_id": run_id,
        "children": [
            {
                "child_run_id": item.child_run_id,
                "node_id": item.node_id,
                "status": "queued",
            }
            for item in receipts
        ],
        "communication": "parent_events_only",
    }
    return ToolResult.success(json.dumps(payload, ensure_ascii=False, sort_keys=True), source="durable_coordinator", capability="child_dispatch")


async def durable_accept_child_candidate_handler(args: Mapping[str, Any], *, coordinator, run_id: str, **_: Any) -> ToolResult:
    child_run_id = str(args.get("child_run_id") or "")
    if not child_run_id:
        return ToolResult.error("child_run_id is required", "[Tool Error] child_run_id is required")
    try:
        result = await coordinator.accept_child_candidate(run_id, child_run_id)
    except (TypeError, ValueError, KeyError) as exc:
        return ToolResult.error(str(exc), f"[Tool Error] candidate acceptance failed: {exc}")
    return ToolResult.success(json.dumps(result, ensure_ascii=False, sort_keys=True), source="durable_coordinator", capability="child_acceptance")


async def durable_reject_child_candidate_handler(args: Mapping[str, Any], *, coordinator, run_id: str, **_: Any) -> ToolResult:
    child_run_id = str(args.get("child_run_id") or "")
    reason = str(args.get("reason") or "")
    if not child_run_id or not reason:
        return ToolResult.error("child_run_id and reason are required", "[Tool Error] child_run_id and reason are required")
    try:
        await coordinator.reject_child_candidate(run_id, child_run_id, reason)
    except (TypeError, ValueError, KeyError) as exc:
        return ToolResult.error(str(exc), f"[Tool Error] candidate rejection failed: {exc}")
    return ToolResult.success(json.dumps({"child_run_id": child_run_id, "status": "rejected"}, sort_keys=True), source="durable_coordinator", capability="child_acceptance")


